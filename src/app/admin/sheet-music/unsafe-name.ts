/**
 * 「这个名字能不能落成文件名 / 库值」的字符判据 —— 与 `pkuso-backend` 是**同一份契约**。
 *
 * 单独成模块的理由与 `sub-parts.ts` / `sections.ts` 相同：这条判据被**跨仓契约**
 * 与**用户手输**两侧夹着，必须能被测试直接 import。它此前内联在 `upload-modal.tsx`
 * 里（常量名 `UNSAFE_IN_PATH`），只有一处调用点、一条测试都没有 —— 于是「后端折叠 NFKC、
 * 前端不折叠」这种口径漂移没有任何东西挡得住（pkuso-web#303）。
 *
 * ## 它守的是什么
 *
 * **不是存储路径**。键是 `{scoreId}/{行 id}.pdf`（见 `upload-modal.tsx` 的 `pathOf`），
 * 声部与乐器名都进不去。守的是另外两处：
 *
 * - `sheet_music_files.file_name` —— 用户下载时经 `a.download` **落到自己文件系统上**的名字
 * - `sheet_music_files.instrument` / `sheet_music_parts.section` 两列的**值**
 *
 * 判据只有一条：**「落不下去」或「落下去之后肉眼分不出来」**。
 * 这条线决定下面每个分支的取舍，也决定了什么**不**收（见「刻意**不**收的两种」）。
 * 两侧的代价是不对称的：跨过这条线的值会造出一个用户看不出问题、也无从改起的名字；
 * 而多拦一个只是让用户手填一次。
 *
 * ## 为什么 raw 与 NFKC 折叠后**两种形态都要判**
 *
 * 两种形态各有对方看不见的东西，只判一种就一定漏：
 *
 * - **折叠会造出问题**：`．.`（全角点 + 半角点）折完就是 `..`；`：＊？＜＞｜＂＼`
 *   折完分别是 `:*?<>|"\` —— 全是文件名里落不下去的字符。判 raw 判不出来。
 * - **折叠会消掉问题**：非空格 `Zs`（U+00A0 NBSP、U+3000 全角空格…）的 NFKC **全是普通
 *   空格**（U+1680 是唯一的例外：它没有兼容分解，折完还是自己），而普通空格是合法的。
 *   只判折叠后的形态，这些字符一个也拦不住 —— 后端此前判的正是折叠后那一份。夹在名字
 *   当中的 NBSP 于是能一路传到文件名与库值里，与真正的空格**肉眼完全同形**
 *   （唯一约束也拦不住：两个值并不相等）。
 *
 *   两端的那类空白轮不到这条判据管：两仓在判之前都会 `.trim()`，而 `trim` 按规范会把
 *   所有 `Zs` 从两端去掉（`\p{Cf}` 不在 `trim` 的范围内 —— 零宽空格在两端也留得下来，
 *   由 `\p{Cf}` 那一支接住）。
 *
 * ⚠️ **`/` 刻意不在此列** —— #12 明确允许「木琴/钟琴」这种合称。
 *
 * ## 刻意**不**收的两种（想加之前先看一眼）
 *
 * - **点**：结尾的点放行 —— `圆号.` 落出来的名字是 `圆号..pdf`，而那个 `..` **不在路径段的
 *   边界上**（名字里没有分隔符），系统不会把它当上跳。也就是说**生成之后的名字没有任何地方
 *   再判一遍**，这条线是有意画在「值」上的。开头的点同理：只在 Unix 系上是隐藏文件，
 *   Windows 上合法。
 * - **普通空格**：`Bass Clarinet` 是正常乐器名，两端的空格由 `editsOf` 的 `.trim()` 收掉。
 */

/**
 * 命中即拦。与 `pkuso-backend/supabase/functions/llm-analyze/analyze.ts` 的同名常量
 * 是**逐字一份**（搜 `UNSAFE_IN_NAME` 定位，别写行号）—— 改一边必须改另一边，
 * 两仓之间**没有任何机制能发现漂移**。
 *
 * 每一支都按上面那条线（「落不下去」或「肉眼分不出来」）收，逐支写清楚拦的是什么：
 *
 * - `\.\.` —— 下载名里的路径上跳（系统与浏览器对它的处理各不相同）
 * - `\p{Cc}` —— 控制字符（NUL 会让整行 insert 失败，而对象已经传上去了 → 桶里一个孤儿对象）
 * - `\p{Cf}` —— 零宽空格 / 软连字符 / BOM：肉眼同名
 * - `\p{Cs}` —— 孤立代理：UTF-8 里编不出来，Postgres 收不下
 * - `\p{Default_Ignorable_Code_Point}` —— **默认不可见的那一整族**（4 千多个码点）：
 *   韩文填充符（U+3164 / U+FFA0 / U+115F）、变体选择符、组合字形连接符（U+034F）…
 *   它们的 Unicode 类别是 `Lo`/`Mn`，所以 `\p{Cf}` 那几支够不着，而**渲染出来是空白**：
 *   一个只填了 U+3164 的乐器名会落成一份肉眼看着没有名字的谱（`editsOf` 与 `isBlankName`
 *   都不认为它空）。后端 `llm-analyze/analyze.ts` 的 `BLANK_LETTERS`（引文归一化）认得的几个
 *   都落在这一族里 —— 这里接的是它的**上位集合**（那段只列了 4 个韩文填充符，不含变体选择符）。
 * - `\u2800` / `\ufffc` —— **属性圈不到、只能点名收**的两个：盲文空格（类别是 `So`）与
 *   对象替换符（粘贴带嵌入对象的富文本时会带上它）。两者的共同点是**字形可能是空白**
 *   而属性上无迹可寻 —— 空白字形是一类**渲染**性质，任何属性都圈不全，所以这一支
 *   是一个**点名清单**，不是一条判据（同族里 U+1D159「乐谱空符头」**有意不收**：
 *   它有可见字形，且在谱务语境里算正当内容）
 * - `(?![ ])\p{Zs}` —— 非普通空格的空白：肉眼同名，且 Windows 会把结尾的它从文件名上吃掉
 * - `\p{Zl}` / `\p{Zp}` —— 行 / 段分隔符：名字里藏着一个看不见的换行
 * - `[\\*?"<>|:]` —— Windows 文件名里非法的字符（`:` 在 NTFS 上会写进**备用数据流**）
 *
 * ⚠️ 这几支里，`(?![ ])\p{Zs}` 那一支**对除 U+1680 以外的非空格 `Zs` 只在判 raw 时有用**
 * （它们的 NFKC 都是普通空格；U+1680 折完还是自己，两种形态都命中）。而 `\.\.` 与
 * `[\\*?"<>|:]` 恰好相反 —— `：＊？＜＞｜＂＼` 这些全角写法折完才现形。
 * 这就是 `findUnsafeInName` 两种形态都判的理由。
 */
const UNSAFE_IN_NAME =
  /\.\.|\p{Cc}|\p{Cf}|\p{Cs}|\p{Default_Ignorable_Code_Point}|[\u2800\ufffc]|(?![ ])\p{Zs}|\p{Zl}|\p{Zp}|[\\*?"<>|:]/u;

/**
 * 上面那几支里**看不见**的那些。
 *
 * 文案里不能只把命中的字符印出来：用户看到的会是一句「有不能用于文件名的「 」，请改掉」，
 * 他照着找也找不到那个字符。
 */
const INVISIBLE_IN_NAME =
  /[\p{Cc}\p{Cf}\p{Cs}\p{Default_Ignorable_Code_Point}\u2800\ufffc\p{Zs}\p{Zl}\p{Zp}]/u;

/**
 * 名字里第一个不能用的东西；没有则 `null`。
 *
 * 返回命中的**原文**（`..` 是两个字符）而不是布尔：调用方要把它写进给用户看的文案里。
 *
 * ⚠️ **必须回到 raw 里去找那个字符**：只判折叠才命中时，直接报折叠后的形态会点名一个
 * 用户手里**根本不存在**的字符（字段里是 `：`、报出去是 `:`），他照着找也找不到 ——
 * 文案给的动作是「改掉」，那就得是他看得见、删得掉的东西。所以命中后逐个原字符折一遍，
 * 报**raw 里折完会出问题的那个**（`圆号…` 报的是 `…`，不是折出来的 `..`）。
 *
 * 逐字符折叠只用来**定位**，不参与判定：折叠是整串的性质（`e` + U+0301 会合成 `é`），
 * 与「哪个原字符折成了非法字符」不是一回事。
 *
 * 只有**连起来折才成**的输入（`．` + `.` 两个字符合起来才是 `..`）没有单一原字符可报，
 * 那一支退回折叠后的形态 —— 此时用户手里的字符与报出来的形态是同一类东西（都是点），
 * 照着改仍然成立。
 */
export function findUnsafeInName(raw: string): string | null {
  // 无 `g` 标志 → 没有 lastIndex 状态，几次 exec 互不影响
  const hit = UNSAFE_IN_NAME.exec(raw)?.[0];
  if (hit) return hit;

  const foldedHit = UNSAFE_IN_NAME.exec(raw.normalize("NFKC"))?.[0];
  if (!foldedHit) return null;
  for (const c of raw) {
    if (UNSAFE_IN_NAME.test(c.normalize("NFKC"))) return c;
  }
  return foldedHit;
}

/**
 * 拦下时给用户的那句话。`field` 传「乐器名」/「声部名」。
 *
 * 不可见字符**报码位**（`U+00A0`）而不是印出字符本身，理由见 `INVISIBLE_IN_NAME`；
 * 而且这种名字用户改不动（看不见就删不掉），所以给的动作是「手工重新输入」——
 * 这类字符多半是从别处**粘贴**带进来的。
 */
export function unsafeNameMessage(field: string, found: string): string {
  if (INVISIBLE_IN_NAME.test(found)) {
    const label = [...found]
      .map((c) => `U+${(c.codePointAt(0) ?? 0).toString(16).toUpperCase().padStart(4, "0")}`)
      .join(" ");
    return `${field}里有看不见的字符（${label}），请手工重新输入`;
  }
  return `${field}里有不能用于文件名的「${found}」，请改掉`;
}
